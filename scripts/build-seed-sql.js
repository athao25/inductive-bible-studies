/* Generates supabase/migrations/0002_seed_content.sql from assets/data/courses.js
 * so the database's course/unit/lesson rows always match the lesson files.
 * Idempotent: every statement upserts on a natural key.
 * Run: node scripts/build-seed-sql.js */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const ORDER = ['john', 'matthew', 'isaiah', 'romans', 'trinity'];

global.window = {};
require(path.join(ROOT, 'assets', 'data', 'courses.js'));
const COURSES = global.window.COURSES;

const q = (s) => "'" + String(s == null ? '' : s).replace(/'/g, "''") + "'";

const out = [
  '-- GENERATED by scripts/build-seed-sql.js — do not edit by hand.',
  '-- Course, unit and lesson rows mirroring assets/data/courses.js.',
  '',
  'begin;',
  ''
];

ORDER.forEach((key, ci) => {
  const c = COURSES[key];
  out.push(`-- ${c.name} — ${c.lessons.length} lessons, ${c.units.length} units`);
  out.push(
    'insert into public.courses (id, name, title, initial, tagline, epigraph, detail, status, position) values',
    `  (${[q(c.key), q(c.name), q(c.title), q(c.initial), q(c.tagline), q(c.epigraph), q(c.detail),
        q(c.status === 'complete' ? 'complete' : 'in progress'), ci + 1].join(', ')})`,
    'on conflict (id) do update set',
    '  name = excluded.name, title = excluded.title, initial = excluded.initial,',
    '  tagline = excluded.tagline, epigraph = excluded.epigraph, detail = excluded.detail,',
    '  status = excluded.status, position = excluded.position;',
    ''
  );

  out.push('insert into public.units (course_id, title, position) values');
  out.push(c.units.map((u, i) => `  (${q(c.key)}, ${q(u.title)}, ${i + 1})`).join(',\n'));
  out.push('on conflict (course_id, position) do update set title = excluded.title;', '');

  const unitOf = {};
  c.units.forEach((u, i) => u.lessons.forEach((f) => { unitOf[f] = i + 1; }));

  out.push(
    'insert into public.lessons (course_id, unit_id, slug, n, title, reference, minutes, verse_ref, verse_text, quiz_count) values'
  );
  out.push(c.lessons.map((l) => {
    const unit = `(select id from public.units where course_id = ${q(c.key)} and position = ${unitOf[l.f] || 1})`;
    return `  (${q(c.key)}, ${unit}, ${q(l.f)}, ${l.n}, ${q(l.title)}, ${q(l.ref)}, ${l.mins}, ${q(l.verseRef)}, ${q(l.verseText)}, ${l.q || 0})`;
  }).join(',\n'));
  out.push(
    'on conflict (course_id, slug) do update set',
    '  unit_id = excluded.unit_id, n = excluded.n, title = excluded.title,',
    '  reference = excluded.reference, minutes = excluded.minutes,',
    '  verse_ref = excluded.verse_ref, verse_text = excluded.verse_text,',
    '  quiz_count = excluded.quiz_count;',
    ''
  );
});

out.push('commit;', '');

const file = path.join(ROOT, 'supabase', 'migrations', '0002_seed_content.sql');
fs.mkdirSync(path.dirname(file), { recursive: true });
fs.writeFileSync(file, out.join('\n'));

const totals = ORDER.map((k) => `${k}:${COURSES[k].lessons.length}`).join(' ');
console.log('wrote supabase/migrations/0002_seed_content.sql —', totals);
